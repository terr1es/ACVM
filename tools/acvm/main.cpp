constexpr const char* kVersion = "0.2.0";

void printUsage(std::ostream& out) {
    out << "ACVM " << kVersion << " - the Axiom compiler and virtual machine\n"
        << "\n"
        << "Usage: acvm <command> [options] <file>\n"
        << "\n"
        << "Commands:\n"
        << "  run <file.ax>      Compile and execute a program\n"
        << "  build <file.ax>    Compile to an .acvm module (-o <path>)\n"
        << "  exec <file.acvm>   Execute a compiled module\n"
        << "  check <file.ax>    Parse and type check only\n"
        << "  tokens <file.ax>   Print the token stream\n"
        << "  ast <file.ax>      Print the syntax tree\n"
        << "  ir <file.ax>       Print the generated bytecode\n"
        << "  disasm <file.acvm> Disassemble a compiled module\n"
        << "  version            Print the compiler version\n"
        << "\n"
        << "Options:\n"
        << "  -o <path>          Output path for 'build'\n"
        << "  --tokens           Dump tokens while compiling\n"
        << "  --ast              Dump the AST while compiling\n"
        << "  --ir               Dump bytecode while compiling\n"
        << "  -O0                No optimization: the instructions IRGen emitted\n"
        << "  -O1                Local peepholes, unreachable code, jump threading\n"
        << "  -O2                Also constant propagation, folding, branch resolution (default)\n"
        << "  -O3                Also store/load forwarding and dead-store removal\n"
        << "  -O4                Also delete safe points and assertions. NOT flow-preserving:\n"
        << "                     process scheduling and event conditions stop working\n"
        << "  --verbose          Same as --tokens --ast --ir\n"
        << "  --no-assert        Disable 'assert' checks (and their arguments)\n"
        << "  --stats            Report how many instructions the program executed\n"
        << "  --stats-detail     Also break the count down per opcode\n"
        << "  --jit               Compile qualifying functions to machine code\n"
        << "  --adb              Run under the Axiom Debugger (interactive prompt)\n"
        << "  --break <spec>     Breakpoint: 'main', 'main:12', 'prog.ax:42', ':42'\n"
        << "  --adb-script <f>   Read debugger commands from a file (implies --adb)\n"
        << "  --                 Everything after this goes to the program\n"
        << "                     (read it with argCount() / argAt(i))\n";
}

std::string withExtension(const std::string& path, const std::string& extension) {
    const std::size_t slash = path.find_last_of("/\\");
    const std::size_t dot = path.find_last_of('.');
    if (dot == std::string::npos || (slash != std::string::npos && dot < slash)) {
        return path + extension;
    }
    return path.substr(0, dot) + extension;
}

/// The directory holding this executable, or an empty path when it cannot be determined.
///
/// From the module rather than `argv[0]`: a bare `acvm` found on `PATH` carries no
/// directory, and a relative one is relative to the caller's working directory.
std::string executableDir() {
#if defined(_WIN32)
    wchar_t buffer[MAX_PATH];
    const DWORD length = GetModuleFileNameW(nullptr, buffer, MAX_PATH);
    if (length == 0 || length == MAX_PATH) {
        return {};
    }
    const std::wstring wide(buffer, length);
    // The function returns the executable's full path, not its directory -- the first
    // version of this returned it unchanged and produced `<exe>/<name>.acvm`.
    return std::filesystem::path(wide).parent_path().string();
#else
    std::error_code error;
    const std::filesystem::path self = std::filesystem::read_symlink("/proc/self/exe", error);
    return error ? std::string() : self.parent_path().string();
#endif
}

/// The payload a packaged application carries beside it, or an empty path.
///
/// A bundle is this executable renamed to the application's name, with `<name>.acvm` in the
/// same directory -- `MyApp.exe` next to `MyApp.acvm`. The check is on the *sibling file*,
/// not on this executable's own name: nothing here needs to know that it was renamed, and a
/// rule keyed on the name would break the moment someone renamed the tool itself.
///
/// Only consulted when no arguments were given, so `acvm run x.ax` in a directory that
/// happens to contain `acvm.acvm` still does what was typed.
std::string siblingPayload(const std::string& argv0) {
    std::string dir = executableDir();
    std::string name = argv0;
    const std::size_t slash = name.find_last_of("/\\");
    if (slash != std::string::npos) {
        name = name.substr(slash + 1);
    }
    if (dir.empty()) {
        dir = ".";
    }
    const std::size_t dot = name.find_last_of('.');
    if (dot != std::string::npos) {
        name = name.substr(0, dot);
    }
    if (name.empty()) {
        return {};
    }
    return withExtension(dir + "/" + name, ".acvm");
}

int usageError(const std::string& message) {
    std::cerr << "acvm: " << message << "\n\n";
    printUsage(std::cerr);
    return 2;
}

